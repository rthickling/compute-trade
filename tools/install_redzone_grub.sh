#!/usr/bin/env bash
# Install a GRUB menu entry for RedZone isolation (docs/redzone.md).
# CPU IDs come from tools/redzone_layout.py so the entry tracks this host.
# Does not change the default boot entry.
set -euo pipefail
ROOT=$(cd "$(dirname "$0")/.." && pwd)
if [[ $(id -u) -ne 0 ]]; then
  exec sudo -- "$0" "$@"
fi

LAYOUT_JSON=$(python3 "$ROOT/tools/redzone_layout.py")
CMDLINE=$(python3 "$ROOT/tools/redzone_layout.py" --cmdline)
MATCHER=$(python3 -c 'import json,sys; print(json.load(sys.stdin)["matcher"])' <<<"$LAYOUT_JSON")
PUBLISHER=$(python3 -c 'import json,sys; print(json.load(sys.stdin)["publisher"])' <<<"$LAYOUT_JSON")
BLUE=$(python3 -c 'import json,sys; print(json.load(sys.stdin)["blue"])' <<<"$LAYOUT_JSON")
HK=$(python3 -c 'import json,sys; print(json.load(sys.stdin)["housekeeping_boot_list"])' <<<"$LAYOUT_JSON")

install -m 0755 /dev/stdin /etc/grub.d/42_redzone <<GRUB
#!/bin/sh
set -e

# Compute Trade RedZone isolation — generated by tools/install_redzone_grub.sh
# matcher=${MATCHER} publisher=${PUBLISHER} blue=${BLUE} housekeeping=${HK}

. /usr/share/grub/grub-mkconfig_lib

linux=\$(ls -1 /boot/vmlinuz-* 2>/dev/null | grep -v '\\.efi\\.signed\$' | sort -V | tail -n 1)
[ -n "\$linux" ] || exit 0
basename=\$(basename "\$linux")
version=\${basename#vmlinuz-}
initrd="/boot/initrd.img-\${version}"
[ -f "\$initrd" ] || initrd=\$(ls -1 /boot/initrd.img-"\${version}" /boot/initramfs-"\${version}".img 2>/dev/null | head -n 1)
root_uuid=\$(findmnt -no UUID / 2>/dev/null || true)
[ -n "\$root_uuid" ] || exit 0

REDZONE_CMDLINE="${CMDLINE}"

gettext_printf "Adding Compute Trade RedZone boot entry for Linux %s\\n" "\${version}" >&2

cat <<MENU
menuentry 'Ubuntu, with Linux \${version} (Compute Trade RedZone)' --class ubuntu --class gnu-linux --class gnu --class os \\\$menuentry_id_option 'gnulinux-redzone-\${version}' {
	recordfail
	load_video
	gfxmode \\\$linux_gfx_mode
	insmod gzio
	if [ "\\\$grub_platform" = efi ]; then
		insmod part_gpt
		insmod ext2
	fi
	search --no-floppy --fs-uuid --set=root \${root_uuid}
	linux	\${linux} root=UUID=\${root_uuid} ro \${REDZONE_CMDLINE}
	initrd	\${initrd}
}
MENU
GRUB

if [[ -f /etc/default/grub ]]; then
  sed -i \
    -e 's/^GRUB_TIMEOUT_STYLE=.*/GRUB_TIMEOUT_STYLE=menu/' \
    -e 's/^GRUB_TIMEOUT=.*/GRUB_TIMEOUT=5/' \
    /etc/default/grub
  grep -q '^GRUB_TIMEOUT_STYLE=' /etc/default/grub || echo 'GRUB_TIMEOUT_STYLE=menu' >> /etc/default/grub
  grep -q '^GRUB_TIMEOUT=' /etc/default/grub || echo 'GRUB_TIMEOUT=5' >> /etc/default/grub
fi

update-grub

echo
echo "Installed. Default boot is unchanged."
echo "At the GRUB menu choose: Ubuntu ... (Compute Trade RedZone)"
echo "Kernel args: ${CMDLINE}"
echo "Runtime defaults: matcher=${MATCHER} publisher=${PUBLISHER} blue=${BLUE}"
